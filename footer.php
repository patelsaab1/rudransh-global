    function setupSubmenuToggle(toggleId, submenuId, iconId) {
        const toggle = document.getElementById(toggleId);
        const submenu = document.getElementById(submenuId);
        const icon = document.getElementById(iconId);

        if (toggle && submenu) {
            toggle.addEventListener('click', (e) => {
                e.stopPropagation();
                submenu.classList.toggle('active');
                if (icon) icon.style.transform = submenu.classList.contains('active') ? 'rotate(180deg)' : 'rotate(0)';
            });
        }
    }

    setupSubmenuToggle('products-toggle', 'products-submenu', 'products-icon');
